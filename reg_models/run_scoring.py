company_stats = pd.read_csv('data/finance.csv')
companies = company_stats['Company']
company_stats['ai_score'] = np.zeros(len(company_stats))
for i, company in enumerate(list(russian_companies_expanded.keys())):
    print(f'Processing company {company}...')
    if not os.path.exists(f'data/firm_scores/{i}_score.csv'):
        cur_emp = vacancies[vacancies['employer_name'].isin(russian_companies_expanded[company])]
        print(len(cur_emp))
        cur_emp_ext = run_model(cur_emp)
        cur_emp_ext.to_csv(f'data/firm_scores/{i}_score.csv')
    else:
        print("Loading scores...")
    cur_emp_ext = pd.read_csv(f'data/firm_scores/{i}_score.csv')
    res = cur_emp_ext[cur_emp_ext['ai_score'] >= 0.05]['ai_score'].sum()
    company_stats.loc[i, 'ai_score'] = res
    print(company, res)
    with open('data/firm_scores/all_score.txt', 'a') as f:
        f.write(f'{res}, ')

company_stats.to_csv('data/finance_lab.csv')